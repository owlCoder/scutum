import type { NextConfig } from "next";

// Osnovna bezbednosna zaglavlja za svaku stranicu. Content-Security-Policy dolazi kasnije, sa nonce-om iz proxy.ts,
// jer Next.js ubacuje inline skripte koje bi stroga politika bez nonce-a blokirala.
const securityHeaders = [
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "no-referrer" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
];

const nextConfig: NextConfig = {
  // Samostalan server (.next/standalone) za mali Docker image bez node_modules.
  output: "standalone",
  poweredByHeader: false,
  cacheComponents: true,
  partialPrefetching: true,
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
